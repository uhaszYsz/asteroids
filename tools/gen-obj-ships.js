/**
 * Convert models/obj/*.obj → models-ship-meshes.js
 * Blender Y-up / long-Z → game +X nose, +Y starboard, +Z up.
 * Usage: node tools/gen-obj-ships.js
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const shipsRoot = path.join(root, 'models', 'obj');
const outPath = path.join(root, 'models-ship-meshes.js');

function normalize(verts, target = 1) {
  let m = 0;
  for (const v of verts) {
    m = Math.max(m, Math.abs(v[0]), Math.abs(v[1]), Math.abs(v[2]));
  }
  const s = m > 0 ? target / m : 1;
  return verts.map((v) => [+(v[0] * s).toFixed(5), +(v[1] * s).toFixed(5), +(v[2] * s).toFixed(5)]);
}

function edgesFromFaces(faces) {
  const seen = new Set();
  const edges = [];
  for (const f of faces) {
    for (let i = 0; i < f.length; i++) {
      const a = f[i];
      const b = f[(i + 1) % f.length];
      const lo = Math.min(a, b);
      const hi = Math.max(a, b);
      const k = lo + ',' + hi;
      if (seen.has(k)) continue;
      seen.add(k);
      edges.push([lo, hi]);
    }
  }
  return edges;
}

function parseObj(text) {
  const rawVerts = [];
  const faces = [];
  for (const line0 of text.split(/\r?\n/)) {
    const line = line0.trim();
    if (!line || line[0] === '#') continue;
    const parts = line.split(/\s+/);
    if (parts[0] === 'v' && parts.length >= 4) {
      rawVerts.push([+parts[1], +parts[2], +parts[3]]);
      continue;
    }
    if (parts[0] === 'f' && parts.length >= 4) {
      const idx = [];
      for (let i = 1; i < parts.length; i++) {
        const a = parts[i].split('/')[0];
        const n = parseInt(a, 10);
        if (!Number.isFinite(n)) continue;
        // OBJ is 1-based; negatives count from end.
        idx.push(n > 0 ? n - 1 : rawVerts.length + n);
      }
      if (idx.length < 3) continue;
      // Fan-triangulate n-gons.
      for (let i = 1; i + 1 < idx.length; i++) {
        faces.push([idx[0], idx[i], idx[i + 1]]);
      }
    }
  }
  // Blender → game: nose = +Z axis in file (ship tip at large +Z).
  const verts = rawVerts.map((v) => [v[2], v[0], v[1]]);
  return { verts, faces };
}

function titleFromId(id) {
  return String(id)
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/([A-Za-z])(\d+)/g, '$1 $2')
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

function collectObjs(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) collectObjs(p, out);
    else if (ent.isFile() && /\.obj$/i.test(ent.name)) out.push(p);
  }
  return out;
}

const files = collectObjs(shipsRoot).sort((a, b) => a.localeCompare(b));
const ships = [];

for (const file of files) {
  const base = path.basename(file, '.obj');
  const text = fs.readFileSync(file, 'utf8');
  const { verts, faces } = parseObj(text);
  if (verts.length < 3 || faces.length < 1) {
    console.warn('skip empty', base);
    continue;
  }
  const nv = normalize(verts, 1);
  let nose = 0;
  let best = -1e9;
  for (let i = 0; i < nv.length; i++) {
    if (nv[i][0] > best) {
      best = nv[i][0];
      nose = i;
    }
  }
  ships.push({
    id: 'obj_' + base.replace(/[^a-z0-9_]+/gi, '_').toLowerCase(),
    name: titleFromId(base),
    source: 'models',
    nose,
    verts: nv,
    faces,
    edges: edgesFromFaces(faces)
  });
}

const body = `/* Auto-generated from models/obj/*.obj — do not edit by hand.
 * Regenerated by: node tools/gen-obj-ships.js
 */
(function (root) {
  const MODEL_SHIP_MESH_DEFS = ${JSON.stringify(ships, null, 2)};
  root.SHIP_MESH_DEFS = (root.SHIP_MESH_DEFS || []).concat(MODEL_SHIP_MESH_DEFS);
})(typeof window !== 'undefined' ? window : globalThis);
`;

fs.writeFileSync(outPath, body);
console.log('Wrote', ships.length, 'ships →', path.relative(root, outPath));
for (const s of ships) {
  console.log(' ', s.id, s.name, s.verts.length + 'v', s.faces.length + 'f');
}
