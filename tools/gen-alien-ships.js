function normalize(verts, target = 1) {
  let m = 0;
  for (const v of verts) {
    m = Math.max(m, Math.abs(v[0]), Math.abs(v[1]), Math.abs(v[2]));
  }
  const s = m > 0 ? target / m : 1;
  return verts.map((v) => [+(v[0] * s).toFixed(5), +(v[1] * s).toFixed(5), +(v[2] * s).toFixed(5)]);
}

function edgesFromFaces(faces) {
  const seen = new Set();
  const edges = [];
  for (const f of faces) {
    for (let i = 0; i < f.length; i++) {
      const a = f[i];
      const b = f[(i + 1) % f.length];
      const lo = Math.min(a, b);
      const hi = Math.max(a, b);
      const k = lo + ',' + hi;
      if (seen.has(k)) continue;
      seen.add(k);
      edges.push([lo, hi]);
    }
  }
  return edges;
}

function add(list, id, name, verts, faces, nose, extraEdges) {
  const nv = normalize(verts, 1);
  const edges = edgesFromFaces(faces);
  if (extraEdges) {
    for (const e of extraEdges) {
      const lo = Math.min(e[0], e[1]);
      const hi = Math.max(e[0], e[1]);
      if (!edges.some((x) => x[0] === lo && x[1] === hi)) edges.push([lo, hi]);
    }
  }
  // Pick forward-most vert as nose if not given.
  let n = nose;
  if (n == null) {
    let best = -1e9;
    n = 0;
    for (let i = 0; i < nv.length; i++) {
      if (nv[i][0] > best) { best = nv[i][0]; n = i; }
    }
  }
  list.push({
    id,
    name,
    source: 'alien',
    nose: n,
    verts: nv,
    faces,
    edges
  });
}

